#!/usr/bin/env python3
"""Generate a SHA-256 manifest for legacy unsigned DLLs shipped in a game package.

Only exact hashes of files present in the release package are emitted. Runtime
acceptance still requires the DLL's basename to be in the C++ compatibility list
and the module to be loaded from the game directory.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "client" / "src" / "digital_signature_validator.cpp"
DEFAULT_OUTPUT = ROOT / "client" / "include" / "unsigned_module_manifest.generated.h"


class ManifestError(Exception):
    pass


def read_allowlist(source_path: Path) -> set[str]:
    try:
        source = source_path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ManifestError(f"cannot read runtime DLL allowlist source: {exc}") from exc
    match = re.search(
        r"m_allowedUnsignedDlls\s*=\s*\{(?P<body>.*?)\};",
        source,
        flags=re.DOTALL,
    )
    if match is None:
        raise ManifestError("cannot locate m_allowedUnsignedDlls in the runtime source")
    names = {name.casefold() for name in re.findall(r'L"([^"\\]+)"', match.group("body"))}
    if not names:
        raise ManifestError("runtime unsigned-DLL allowlist is empty or malformed")
    if any(not name.isascii() or "/" in name or "\\" in name for name in names):
        raise ManifestError("runtime unsigned-DLL allowlist names must be ASCII basenames")
    return names


def digest_file(path: Path) -> str:
    digest = hashlib.sha256()
    try:
        with path.open("rb") as file:
            while True:
                chunk = file.read(1024 * 1024)
                if not chunk:
                    break
                digest.update(chunk)
    except OSError as exc:
        raise ManifestError(f"cannot read {path.name}: {exc}") from exc
    return digest.hexdigest()


def collect_entries(game_directory: Path, names: set[str]) -> list[tuple[str, str]]:
    game_directory = game_directory.resolve()
    if not game_directory.is_dir():
        raise ManifestError(f"game directory does not exist or is not a directory: {game_directory}")
    entries: set[tuple[str, str]] = set()
    try:
        for path in game_directory.rglob("*"):
            if path.is_symlink():
                raise ManifestError(f"symlinks are not accepted in the production package: {path}")
            if not path.is_file() or path.name.casefold() not in names:
                continue
            entries.add((path.name.casefold(), digest_file(path)))
    except OSError as exc:
        raise ManifestError(f"cannot enumerate package: {exc}") from exc
    return sorted(entries)


def render_header(entries: list[tuple[str, str]]) -> str:
    output = [
        "#pragma once",
        "",
        "// Generated by tools/generate_unsigned_module_manifest.py from the exact release package.",
        "// Do not hand-edit hashes. Regenerate after changing any shipped allowlisted module.",
        "#define OBLIVION_UNSIGNED_MODULE_MANIFEST_READY 1",
        "",
        "namespace Oblivion::UnsignedModuleManifest {",
        "struct Entry { const wchar_t* moduleName; const char* sha256; };",
        "inline constexpr bool kReady = OBLIVION_UNSIGNED_MODULE_MANIFEST_READY == 1;",
        "inline constexpr Entry kEntries[] = {",
    ]
    if entries:
        for name, digest in entries:
            output.append(f'    {{L"{name}", "{digest}"}},')
    else:
        output.append('    {L"__none__", "PLACEHOLDER"},')
    output.extend([
        "};",
        f"inline constexpr std::size_t kEntryCount = {len(entries)};",
        "} // namespace Oblivion::UnsignedModuleManifest",
        "",
    ])
    return "\n".join(output)


def write_atomically(output_path: Path, contents: str) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="ascii", newline="\n",
            dir=output_path.parent, prefix=output_path.name + ".", suffix=".tmp",
            delete=False,
        ) as target:
            temporary = target.name
            target.write(contents)
            target.flush()
            os.fsync(target.fileno())
        os.replace(temporary, output_path)
        temporary = None
    except OSError as exc:
        raise ManifestError(f"cannot write manifest header: {exc}") from exc
    finally:
        if temporary is not None:
            try:
                os.unlink(temporary)
            except OSError:
                pass


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate the unsigned-module SHA-256 allowlist from an exact game package."
    )
    parser.add_argument("game_directory", type=Path)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    try:
        names = read_allowlist(args.source)
        entries = collect_entries(args.game_directory, names)
        header = render_header(entries)
        write_atomically(args.output, header)
    except ManifestError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    print(f"Generated unsigned-module SHA-256 manifest: {args.output}")
    print(f"Covered {len(entries)} package module variant(s).")
    for name, digest in entries:
        print(f"{name}\t{digest}")
    print("Run the production preflight and rebuild the client before deployment.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
