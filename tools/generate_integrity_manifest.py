#!/usr/bin/env python3
"""Generate the compile-time file-integrity manifest from a real game package.

The generated header contains only SHA-256 hex digests for RRO.exe, en.grf,
and DATA.ini. No hash is invented: generation fails if any required file is
missing, unreadable, or a symlink.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sys
import tempfile
from pathlib import Path
from typing import Iterable

REQUIRED_FILES = (
    ("RRO.exe", "OBLIVION_FILE_HASH_RRO_EXE"),
    ("en.grf", "OBLIVION_FILE_HASH_EN_GRF"),
    ("DATA.ini", "OBLIVION_FILE_HASH_DATA_INI"),
)
DEFAULT_OUTPUT = (
    Path(__file__).resolve().parent.parent
    / "client"
    / "include"
    / "file_integrity_manifest.generated.h"
)
RUNTIME_HASH_LIMIT_BYTES = 512 * 1024 * 1024


class ManifestError(Exception):
    """Raised for an invalid package or output operation."""


def calculate_sha256(path: Path) -> tuple[str, int]:
    digest = hashlib.sha256()
    size = 0
    try:
        with path.open("rb") as source:
            while True:
                chunk = source.read(1024 * 1024)
                if not chunk:
                    break
                size += len(chunk)
                digest.update(chunk)
    except OSError as exc:
        raise ManifestError(f"cannot read {path.name}: {exc}") from exc
    return digest.hexdigest(), size


def render_header(entries: Iterable[tuple[str, str, str]]) -> str:
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/generate_integrity_manifest.py from the exact client package.",
        "// Do not hand-edit these digests. Regenerate after each production package change.",
        "// Enforcement will refuse to start while any entry is missing or invalid.",
    ]
    for filename, macro, digest_and_size in entries:
        # Digest and file size are supplied by calculate_sha256; only the digest is compiled in.
        digest = str(digest_and_size)
        lines.append(f'#define {macro} "{digest}"')
    lines.append("")
    return "\n".join(lines)


def write_atomically(output_path: Path, contents: str) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temp_name = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="ascii",
            newline="\n",
            dir=output_path.parent,
            prefix=output_path.name + ".",
            suffix=".tmp",
            delete=False,
        ) as destination:
            temp_name = destination.name
            destination.write(contents)
            destination.flush()
            os.fsync(destination.fileno())
        os.replace(temp_name, output_path)
        temp_name = None
    except OSError as exc:
        raise ManifestError(f"cannot write generated header {output_path}: {exc}") from exc
    finally:
        if temp_name is not None:
            try:
                os.unlink(temp_name)
            except OSError:
                pass


def generate_manifest(game_directory: Path, output_path: Path) -> list[tuple[str, str, str, int]]:
    game_directory = game_directory.resolve()
    if not game_directory.is_dir():
        raise ManifestError(f"game directory does not exist or is not a directory: {game_directory}")

    values: list[tuple[str, str, str, int]] = []
    errors: list[str] = []
    for filename, macro in REQUIRED_FILES:
        path = game_directory / filename
        if path.is_symlink():
            errors.append(f"{filename}: symlinks are not accepted; provide the actual packaged file")
            continue
        if not path.is_file():
            errors.append(f"{filename}: required production file is missing")
            continue
        try:
            digest, size = calculate_sha256(path)
            values.append((filename, macro, digest, size))
        except ManifestError as exc:
            errors.append(str(exc))

    if errors:
        raise ManifestError("manifest was not written:\n  - " + "\n  - ".join(errors))

    # The runtime currently refuses to enforce a file larger than 512 MiB.
    # Warn here so the operator does not mistake a generated digest for a fully
    # enforceable manifest without reviewing that separate runtime limit.
    oversized = [
        f"{filename} is {size / (1024 * 1024):.1f} MiB; runtime limit is "
        f"{RUNTIME_HASH_LIMIT_BYTES // (1024 * 1024)} MiB"
        for filename, _, _, size in values
        if size > RUNTIME_HASH_LIMIT_BYTES
    ]
    if oversized:
        print(
            "WARNING: hashes were generated, but enforcement will stop on oversized files. "
            "Review kMaxHashFileSizeBytes before enabling enforcement:\n  - "
            + "\n  - ".join(oversized),
            file=sys.stderr,
        )

    # Header macros are ordered and fixed; values are fully computed before output is replaced.
    entry_map = {macro: (filename, digest, size) for filename, macro, digest, size in values}
    header_entries = [
        (filename, macro, entry_map[macro][1])
        for filename, macro in REQUIRED_FILES
    ]
    write_atomically(output_path, render_header(header_entries))
    return values


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Compute real SHA-256 hashes for the client file-integrity manifest."
    )
    parser.add_argument(
        "game_directory",
        type=Path,
        help="directory containing the exact RRO.exe, en.grf, and DATA.ini production files",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"generated header path (default: {DEFAULT_OUTPUT})",
    )
    args = parser.parse_args()

    try:
        values = generate_manifest(args.game_directory, args.output)
    except ManifestError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    print(f"Generated integrity manifest: {args.output}")
    for filename, _, digest, size in values:
        print(f"{filename}\t{size} bytes\tSHA256 {digest}")
    print("Rebuild the client from this header; do not enable enforcement before reviewing warnings.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
